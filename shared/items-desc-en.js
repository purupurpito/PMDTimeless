// Exclusivos (470): siguen unas pocas plantillas, así que se generan desde sus datos (especies, estadísticas, tipo que absorben)
const STAT_EN = { atk: 'Attack', def: 'Defense', spa: 'Sp. Atk', spd: 'Sp. Def' };
const spEn = sp => SPECIES_EN[sp] || POKEDEX[sp]?.name || sp;
for (const [name, it] of Object.entries(EXCLUSIVES)) {
  const who = [...new Set(it.species.map(spEn))].join(', ');
  const stats = it.boosts.map(([s]) => STAT_EN[s]).filter(Boolean);
  ITEM_DESC_EN[name] = it.absorb ? `Absorbs damage from ${TYPE_EN[it.absorb] || it.absorb}-type moves to restore HP. For: ${who}. Works from the Bag.`
    : stats.length ? `Slightly raises ${stats.join(' and ')}. For: ${who}. Works from the Bag.`
    : `Exclusive item for: ${who}. (Its special effect isn't available yet.)`;
}
